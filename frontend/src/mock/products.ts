function crackersProduct(
  id: string,
  name: string,
  sku: string,
  category: string,
  brand: string,
  unit: string,
  purchasePrice: number,
  sellingPrice: number,
  stock: number,
  minStock: number,
  gstRate: number,
  hsn: string,
  productType: string,
  piecesPerBox: number,
  bulkPricing: { from: number; to: number | null; price: number }[],
): Product {
  const boxQty = Math.max(1, piecesPerBox)
  return {
    id,
    name,
    sku,
    barcode: `89010${String(Math.abs(Number(id.replace(/\D/g, '')) || 100) + 5000)}00`,
    category,
    brand,
    unit,
    purchasePrice,
    sellingPrice,
    mrp: Math.round(sellingPrice * 1.08),
    wholesalePrice: sellingPrice * 0.92,
    taxType: 'gst',
    gstRate,
    hsn,
    openingStock: stock,
    currentStock: stock,
    minStock,
    godown: 'Main Godown',
    status: 'active',
    isCrackers: true,
    crackers: {
      productType,
      boxQuantity: boxQty,
      piecesPerBox,
      purchaseUnit: 'Box',
      sellingUnit: 'Piece',
      wholesalePrice: purchasePrice * 0.95,
      retailPrice: sellingPrice,
      seasonalPrice: Math.round(sellingPrice * 1.15),
      bulkPricing: bulkPricing.map((tier, i) => ({ id: `${id}-t${i}`, ...tier })),
    },
    createdAt: now,
  }
}

